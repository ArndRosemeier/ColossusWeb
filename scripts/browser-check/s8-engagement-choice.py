#!/usr/bin/env python3
"""S8's browser-level check: the DEFENDER's pre-battle choice, in two clients.

Why this exists. The owner hit this LIVE, mid-game, in a two-browser game: he
clicked "Fight!" and got the battleground immediately, while the other player was
never offered the chance to give up. A DOM-free suite cannot see "whose client
shows which button"; this check drives the REAL built app in headless Chrome
against a fake ServerStore on the same origin, one browser per SEAT, and reads
the DOM the owner watches.

What it proves, mode by mode:

  host (seat 0, the ATTACKER — the mover whose Turn it is)
   1. the app resumes the game and the board renders;
   2. pressing "Start engagement" opens the engagement and the overlay appears;
   3. the attacker's overlay says it is WAITING on the defender and offers NO
      battle button — the exact button that stole the defender's decision;
   4. a force-dispatched `proposeAgreement{fight}` (the removed code path) is
      REFUSED: the phase stays `Fight`, no battle exists, and nothing is
      published to the store;
   5. the engagement window is the defender's, so the attacker's own Flee is
      never offered either.

  guest (seat 1, the DEFENDER)
   6. the defender's client is the one asked: "Stand and fight" and "Flee" are
      both on screen, and no battle button is;
   7. the defender is told it is the attacker's legion attacking;
   8. once the defender stands, the window closes for the whole table — the
      client's own overlay now offers the battle, and the state it holds says
      `fleeDeclined`, so a battle can begin;
   9. the resolution is PUBLISHED (the defender's answer reaches the attacker's
      client through the store, as the app's ONE commit path does it).

No key material is used (the keys are made-up strings containing `testonly`) and
no request leaves this box. The Chrome tree is killed in `finally`, success and
failure alike.

Run it after a subpath-free build:

  (cd web && npx vitest run --config scripts/browser-check/vitest.config.s8.ts)
  (cd web && VITE_SERVERSTORE_URL=/storeapi npx vite build \\
      --outDir ../scripts/browser-check/s8-dist --emptyOutDir)
  python3 scripts/browser-check/s8-engagement-choice.py host
  python3 scripts/browser-check/s8-engagement-choice.py guest

The fixture (`scripts/browser-check/s8-fixture.json`) is GENERATED by the real
engine and is gitignored scratch.
"""

